// Command slice-layout discovers command slices for depguard and domain coverage.
// It reads package clauses only; the pinned depguard checks imports.
package main

import (
	"encoding/json"
	"errors"
	"fmt"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"
)

const rulesSlot = "      rules: {} # generated by tools/bin/check-slice-layout\n"

type sourcePackage struct {
	path          string
	externalTests []string
}

type slice struct {
	path     string
	domains  []sourcePackage
	adapters map[string][]sourcePackage
}

type denial struct {
	Package     string `json:"pkg"`
	Description string `json:"desc"`
}

type rule struct {
	Mode  string   `json:"list-mode"`
	Files []string `json:"files"`
	Allow []string `json:"allow,omitempty"`
	Deny  []denial `json:"deny"`
}

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "slice-layout:", err)
		os.Exit(1)
	}
}

func run(args []string) (err error) {
	if len(args) != 2 || (args[0] != "domains" && args[0] != "config") {
		return fmt.Errorf("usage: slice-layout domains <root> | config <root>")
	}
	root, err := filepath.Abs(args[1])
	if err != nil {
		return err
	}
	source, err := os.OpenRoot(root)
	if err != nil {
		return err
	}
	defer func() { err = errors.Join(err, source.Close()) }()
	layout, err := discover(source.FS())
	if err != nil {
		return err
	}
	if args[0] == "domains" {
		var packages []string
		for _, s := range layout {
			for _, pkg := range s.domains {
				packages = append(packages, "./"+pkg.path)
			}
		}
		if len(packages) == 0 {
			return fmt.Errorf("no domain packages discovered under internal/")
		}
		slices.Sort(packages)
		for _, pkg := range slices.Compact(packages) {
			fmt.Println(pkg)
		}
		return nil
	}
	module, err := modulePath(root)
	if err != nil {
		return err
	}
	base, err := source.ReadFile(".golangci.yml")
	if err != nil {
		return err
	}
	config := strings.ReplaceAll(string(base), "\r\n", "\n")
	if strings.Count(config, rulesSlot) != 1 {
		return fmt.Errorf(".golangci.yml must contain exactly one generated depguard rules slot")
	}
	// JSON is a YAML mapping. Only the explicit rules slot is replaced, so
	// every other linter, exclusion, formatter and threshold stays in force.
	rules, err := json.MarshalIndent(makeRules(module, layout), "      ", "  ")
	if err != nil {
		return err
	}
	config = strings.Replace(config, rulesSlot, "      rules: "+string(rules)+"\n", 1)
	_, err = fmt.Print(config)
	return err
}

func modulePath(root string) (string, error) {
	// Ask the existing Go tool to read go.mod; no second module-file parser.
	cmd := exec.Command("go", "mod", "edit", "-json")
	cmd.Dir = root
	data, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("read module from go.mod: %w", err)
	}
	var mod struct{ Module struct{ Path string } }
	if err := json.Unmarshal(data, &mod); err != nil {
		return "", err
	}
	if mod.Module.Path == "" {
		return "", fmt.Errorf("go.mod has no module path")
	}
	return mod.Module.Path, nil
}

// visible matches the source directories Go walks, excluding fixture trees and
// tool caches even when they sit beneath a domain.
func visible(name string) bool {
	return name != "testdata" && name != "vendor" && !strings.HasPrefix(name, ".") && !strings.HasPrefix(name, "_")
}

func discover(source fs.FS) ([]slice, error) {
	entries, err := fs.ReadDir(source, "internal")
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var result []slice
	for _, entry := range entries {
		if !entry.IsDir() || !visible(entry.Name()) {
			continue
		}
		path := "internal/" + entry.Name()
		children, err := fs.ReadDir(source, path)
		if err != nil {
			return nil, err
		}
		isSlice := false
		for _, child := range children {
			isSlice = isSlice || (child.IsDir() && (child.Name() == "domain" || child.Name() == "port"))
		}
		if !isSlice {
			continue
		}
		s := slice{path: path, adapters: make(map[string][]sourcePackage)}
		for _, child := range children {
			if !child.IsDir() || !visible(child.Name()) || child.Name() == "port" || child.Name() == "command" {
				continue
			}
			packages, err := packageTree(source, path+"/"+child.Name())
			if err != nil {
				return nil, err
			}
			if child.Name() == "domain" {
				s.domains = packages
			} else {
				s.adapters[path+"/"+child.Name()] = packages
			}
		}
		result = append(result, s)
	}
	return result, nil
}

func packageTree(source fs.FS, path string) ([]sourcePackage, error) {
	var result []sourcePackage
	err := fs.WalkDir(source, path, func(dir string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if !entry.IsDir() {
			return nil
		}
		if !visible(entry.Name()) {
			return filepath.SkipDir
		}
		files, err := fs.ReadDir(source, dir)
		if err != nil {
			return err
		}
		pkg := sourcePackage{path: dir}
		found := false
		sourceNames := make(map[string]bool)
		testNames := make(map[string]string)
		for _, file := range files {
			if file.IsDir() || !visible(file.Name()) || !strings.HasSuffix(file.Name(), ".go") {
				continue
			}
			found = true
			// Only external tests get the exact subject-package exception. No
			// imports are parsed here: depguard remains the import checker.
			filename := dir + "/" + file.Name()
			data, err := fs.ReadFile(source, filename)
			if err != nil {
				return err
			}
			parsed, err := parser.ParseFile(token.NewFileSet(), filename, data, parser.PackageClauseOnly)
			if err != nil {
				return err
			}
			if strings.HasSuffix(file.Name(), "_test.go") {
				testNames[file.Name()] = parsed.Name.Name
			} else {
				sourceNames[parsed.Name.Name] = true
			}
		}
		for file, name := range testNames {
			if strings.HasSuffix(name, "_test") && sourceNames[strings.TrimSuffix(name, "_test")] {
				pkg.externalTests = append(pkg.externalTests, pkg.path+"/"+file)
			}
		}
		slices.Sort(pkg.externalTests)
		if found {
			result = append(result, pkg)
		}
		return nil
	})
	return result, err
}

// Exact package plus slash-prefixed descendants, never a lookalike name.
func subtree(path string) []string { return []string{path + "$", path + "/"} }

func denyTree(path, reason string) []denial {
	var result []denial
	for _, prefix := range subtree(path) {
		result = append(result, denial{prefix, reason})
	}
	return result
}

func glob(path string) string {
	// File names are literals inside globs, including any metacharacters.
	escape := strings.NewReplacer("\\", "\\\\", "*", "\\*", "?", "\\?", "[", "\\[", "]", "\\]", "{", "\\{", "}", "\\}")
	return "**/" + escape.Replace(path)
}

func makeRules(module string, layout []slice) map[string]rule {
	rules := make(map[string]rule)
	rapid := rule{Mode: "lax", Files: []string{"$all"}, Deny: []denial{{"pgregory.net/rapid", "rapid is used only by domain property tests"}}}
	var adapters []string
	for _, s := range layout {
		for adapter := range s.adapters {
			adapters = append(adapters, adapter)
		}
	}
	slices.Sort(adapters)
	for _, s := range layout {
		domain := rule{Mode: "lax", Files: []string{glob(s.path+"/domain") + "/**"}}
		// Preserve the existing os/net family bans, not just four imports.
		domain.Deny = []denial{{"os", "the domain reaches files through its port"}, {"net", "the domain does no I/O"}}
		for _, adapter := range adapters {
			domain.Deny = append(domain.Deny, denyTree(module+"/"+adapter, "the domain reaches adapters through ports")...)
		}
		for _, target := range []string{s.path + "/command", "internal/cli"} {
			domain.Deny = append(domain.Deny, denyTree(module+"/"+target, "the domain knows no command or UI")...)
		}
		rules[s.path+"/domain"] = domain
		rapid.Files = append(rapid.Files, "!"+glob(s.path+"/domain")+"/*_test.go", "!"+glob(s.path+"/domain")+"/**/*_test.go")
		foreign := rule{Mode: "lax", Files: []string{glob(s.path) + "/**"}}
		for _, other := range layout {
			if s.path != other.path {
				foreign.Deny = append(foreign.Deny, denyTree(module+"/"+other.path+"/domain", "a slice must not import another slice's domain")...)
			}
		}
		if len(foreign.Deny) != 0 {
			rules[s.path+"/foreign-domains"] = foreign
		}
		for adapter, packages := range s.adapters {
			guard := rule{
				Mode: "lax", Files: []string{glob(adapter) + "/**"},
				Allow: subtree(module + "/" + s.path + "/port"),
				Deny:  denyTree(module, "an adapter imports only its own port within the module"),
			}
			for _, pkg := range packages {
				if len(pkg.externalTests) == 0 {
					continue
				}
				external := guard
				external.Files = nil
				external.Allow = append(slices.Clone(guard.Allow), module+"/"+pkg.path+"$")
				for _, file := range pkg.externalTests {
					guard.Files = append(guard.Files, "!"+glob(file))
					external.Files = append(external.Files, glob(file))
				}
				rules[pkg.path+"/external-tests"] = external
			}
			rules[adapter] = guard
		}
	}
	rules["rapid"] = rapid
	return rules
}
